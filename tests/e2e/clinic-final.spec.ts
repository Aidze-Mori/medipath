import { expect, test } from './test';
import { openDemoClinic, returnToWorkMode } from './helpers';

for (const width of [320, 390, 1440]) test(`clinic notification and explicit staff feedback ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/clinic');
  await openDemoClinic(page);
  await page.getByRole('button', { name: /Анна Соколова/ }).click();
  await page.screenshot({ path: test.info().outputPath('clinic-workspace.png'), fullPage: false });
  await page.getByRole('button', { name: 'Уведомить пациента', exact: true }).click();
  const notifications = page.getByRole('dialog').filter({ has: page.getByRole('combobox', { name: 'Повод уведомления' }) });
  await notifications.getByRole('button', { name: 'SMS', exact: true }).click();
  await notifications.getByRole('button', { name: 'Показать демоуведомление' }).click();
  const preview = page.getByRole('dialog', { name: 'Демоуведомление', exact: true });
  await expect(preview.getByText('Никакое SMS или push-сообщение не отправлялось.', { exact: false })).toBeVisible();
  await preview.getByRole('button', { name: 'Закрыть окно' }).click();
  await notifications.getByRole('button', { name: 'Показать демоуведомление' }).click();
  await preview.getByRole('button', { name: 'Закрыть окно' }).click();
  await expect(notifications.getByText('Журнал уведомлений · 1')).toBeVisible();
  await notifications.getByRole('combobox', { name: 'Повод уведомления' }).click();
  await page.getByRole('option', { name: 'Вернуться в личный кабинет', exact: true }).click();
  await expect(notifications.getByText('Будем рады видеть вас снова')).toBeVisible();
  await notifications.getByRole('combobox', { name: 'Повод уведомления' }).click();
  await page.getByRole('option', { name: 'Есть рекомендация без записи', exact: true }).click();
  await expect(notifications.getByText('Ваш план посещений', { exact: true })).toBeVisible();

  await notifications.getByRole('button', { name: 'Закрыть окно' }).click();
  await page.getByRole('button', { name: 'Обратная связь', exact: true }).click();
  const feedback = page.getByRole('dialog', { name: 'Обратная связь по результату', exact: true });
  await feedback.getByRole('combobox', { name: 'Роль сотрудника' }).click();
  await page.getByRole('option', { name: 'Врач', exact: true }).click();
  await feedback.getByRole('button', { name: 'Сообщить о проблеме' }).click();
  const form = page.getByRole('dialog', { name: 'Сообщить о проблеме', exact: true });
  await form.getByRole('button', { name: 'Сохранить отзыв в демо' }).click();
  await expect(form.getByText('Добавьте комментарий от 5 до 500 символов.')).toBeVisible();
  await form.getByRole('radio', { name: 'Источник', exact: true }).check();
  await form.getByLabel('Комментарий', { exact: false }).fill('Уточнить формулировку учебного источника.');
  await form.getByRole('button', { name: 'Сохранить отзыв в демо' }).click();
  await expect(feedback.getByText('Замечание врача · Источник')).toBeVisible();
  await expect(feedback.getByText('Новое', { exact: true })).toBeVisible();
  await feedback.getByRole('button', { name: 'Взять на рассмотрение' }).click();
  await expect(feedback.getByText('На рассмотрении', { exact: true })).toBeVisible();
  await feedback.getByRole('button', { name: 'Закрыть с результатом' }).click();
  const resolution = page.getByRole('dialog', { name: 'Результат разбора', exact: true });
  await resolution.getByRole('button', { name: 'Закрыть замечание' }).click();
  await expect(resolution.getByText('Для закрытия укажите результат разбора от 5 до 500 символов.')).toBeVisible();
  await resolution.getByLabel('Результат разбора', { exact: true }).fill('Учебный источник проверен в демонстрации.');
  await resolution.getByRole('button', { name: 'Закрыть замечание' }).click();
  await expect(feedback.getByText('Закрыто', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await feedback.scrollIntoViewIfNeeded();
  await page.screenshot({ path: test.info().outputPath('clinic-demo.png'), fullPage: false });

  await feedback.getByRole('button', { name: 'Закрыть окно' }).click();
  await returnToWorkMode(page);
  await expect(page.getByText('Уточнить формулировку учебного источника.')).toHaveCount(0);
  await openDemoClinic(page);
  await page.getByRole('button', { name: /Обратная связь/ }).click();
  await expect(page.getByText('Уточнить формулировку учебного источника.')).toBeVisible();
  expect(errors).toEqual([]);
});
