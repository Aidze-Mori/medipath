import { chooseOption } from './helpers';
import { expect, test, type Page } from './test';
async function demoPanel(page: Page) {
  await page.getByRole('button', { name: 'Демопанель', exact: true }).click();
  return page.getByRole('dialog', { name: 'Демопанель', exact: true });
}

for (const width of [1440, 390]) test(`complete clinic results, planning, feedback and archive ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('dialog', (dialog) => dialog.accept());
  await page.goto('/patient');
  const panel = await demoPanel(page);
  await panel.getByText('Дополнительные сценарии и настройки', { exact: true }).click();
  await chooseOption(panel.getByLabel('Режим обработки примера'), 'local');
  const clinicResponse = page.waitForResponse((response) => response.url().includes('/api/clinic-demo?') && response.status() === 200);
  await panel.getByRole('button', { name: 'Результаты из клиники', exact: true }).click();
  expect((await clinicResponse).request().method()).toBe('GET');
  await expect(page.getByRole('heading', { name: 'Ваши результаты', exact: true })).toBeVisible();
  await expect(page.getByRole('checkbox')).toHaveCount(3);
  await expect(page.getByRole('button', { name: 'Подтвердить текст и создать маршрут' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Собрать маршрут', exact: true })).toBeDisabled();
  await expect(page.locator('time').first()).toHaveText(/октября 2026/);
  await page.getByRole('checkbox', { name: 'Учесть в маршруте: КТ грудной клетки', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Учесть в маршруте: Маммография', exact: true }).check();
  await expect(page.getByText('документов выбрано', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('results-library.png'), fullPage: true });
  await page.getByRole('button', { name: 'Собрать маршрут', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'План посещений', exact: true })).toBeVisible();
  const pulmonology = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Консультация пульмонолога', exact: true }) });
  const mammology = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Консультация маммолога', exact: true }) });
  await mammology.getByRole('button', { name: 'Выбрать позже', exact: true }).click();
  await expect(mammology.getByText('Выбор отложен · записи пока нет')).toBeVisible();
  await pulmonology.getByRole('button', { name: 'Выбрать врача', exact: true }).click();
  const picker = page.getByRole('dialog');
  await picker.getByRole('button', { name: '09:00', exact: true }).first().click();
  await picker.getByRole('button', { name: 'Продолжить', exact: true }).click();
  await picker.getByRole('button', { name: 'Подтвердить демозапись', exact: true }).click();
  await expect(page.locator('.study-booked-label')).toContainText('Вы записаны');
  await page.locator('.route-study.is-booked > summary').click();
  await expect(page.getByText('Демозапись создана. Клиника не получала заявку.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Завершить планирование', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Маршрут завершён', exact: true })).toBeVisible();
  await expect(page.getByText('Выбор врача отложен', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Скачать календарь маршрута', exact: true })).toHaveCount(1);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Скачать календарь маршрута', exact: true }).click();
  expect((await downloadEvent).suggestedFilename()).toBe('medipath-plan.ics');

  const navigation = page.getByRole('navigation', { name: width < 768 ? 'Навигация на телефоне' : 'Основная навигация', exact: true });
  await navigation.getByRole('button', { name: 'Моя медкарта', exact: true }).click();
  await page.getByRole('button', { name: 'Открыть результат: КТ грудной клетки', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Данные исследования', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Пояснение к результату', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Полезно', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Полезно', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Не помогло', exact: true }).click();
  await page.getByRole('button', { name: 'Снять оценку', exact: true }).click();
  await page.getByRole('button', { name: 'Полезно', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('result-details.png'), fullPage: true });
  await page.getByRole('button', { name: 'Демопанель', exact: true }).click();
  await page.getByRole('link', { name: 'Клинике', exact: true }).click();
  await page.getByRole('button', { name: /Анна Соколова/ }).click();
  await page.getByRole('button', { name: 'Обратная связь', exact: true }).click();
  const staffFeedback = page.getByRole('dialog', { name: 'Обратная связь по результату', exact: true });
  await expect(staffFeedback.getByText('Пояснение полезно', { exact: false })).toBeVisible();
  await staffFeedback.getByRole('button', { name: 'Закрыть окно', exact: true }).click();
  await page.getByRole('button', { name: 'Уведомить пациента', exact: true }).click();
  const notifications = page.getByRole('dialog').filter({ has: page.getByRole('combobox', { name: 'Повод уведомления' }) });
  await chooseOption(notifications.getByLabel('Повод уведомления'), 'unbooked');
  await expect(notifications.getByRole('button', { name: 'Создать предложение в демо', exact: true })).toBeDisabled();
  await chooseOption(notifications.getByLabel('Повод уведомления'), 'result_ready');
  await notifications.getByRole('button', { name: 'Показать демоуведомление', exact: true }).click();
  await page.getByRole('dialog', { name: 'Демоуведомление', exact: true }).getByRole('button', { name: 'Открыть результат пациента', exact: true }).click();
  await expect(page).toHaveURL(/\/patient/);
  await expect(page.getByRole('heading', { name: 'Ваши результаты', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'В архив: КТ грудной клетки', exact: true }).click();
  await expect(page.getByRole('checkbox')).toHaveCount(2);
  await navigation.getByRole('button', { name: 'Архив', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Архив документов', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Открыть результат: КТ грудной клетки', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Собрать маршрут', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Редактировать текст', exact: true }).click();
  await page.getByRole('button', { name: 'Создать маршрут по результату', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Сначала верните документ из архива');
  await navigation.getByRole('button', { name: 'Архив', exact: true }).click();
  await page.getByRole('button', { name: 'Вернуть в результаты: КТ грудной клетки', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'В архиве пока пусто', exact: true })).toBeVisible();
  await navigation.getByRole('button', { name: 'Моя медкарта', exact: true }).click();
  await expect(page.getByRole('checkbox')).toHaveCount(3);

  const resetPanel = await demoPanel(page);
  await resetPanel.getByRole('button', { name: 'Сбросить демоданные', exact: true }).click();
  await resetPanel.getByRole('button', { name: 'Результаты из клиники', exact: true }).click();
  await expect(page.getByRole('checkbox')).toHaveCount(3);
  await expect(page.getByRole('checkbox', { checked: true })).toHaveCount(0);
  await navigation.getByRole('button', { name: 'Записи', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Здесь появятся ваши демозаписи', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
